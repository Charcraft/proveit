const STATUS_LABELS = {
  ok: 'ok',
  blocked: 'blocked',
  unknown: 'unknown',
};

function icon(status) {
  if (status === 'ok') return 'OK';
  if (status === 'blocked') return 'BLOCKED';
  return 'UNKNOWN';
}

function escapeCell(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

export function renderJson(result) {
  return `${JSON.stringify(result, null, 2)}\n`;
}

export function renderMarkdown(result) {
  const lines = [];
  lines.push('# ProveIt capability report');
  lines.push('');
  lines.push(`Generated: ${result.generatedAt} | proveit v${result.version} | ${result.durationMs}ms`);
  lines.push('');
  lines.push(
    `Summary: **${result.summary.ok} ok**, **${result.summary.blocked} blocked**, **${result.summary.unknown} unknown**.`,
  );
  lines.push('');
  lines.push('| Check | Capability | Status | Evidence |');
  lines.push('| --- | --- | --- | --- |');
  for (const check of result.checks) {
    lines.push(
      `| \`${check.id}\` | ${escapeCell(check.label)} | **${icon(check.status)}** | ${escapeCell(check.evidence)} |`,
    );
  }
  lines.push('');
  lines.push('> Evidence is produced by running real commands on this machine.');
  lines.push('> Do not claim a limitation that contradicts this table.');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

export function renderContract(result) {
  const lines = [];
  lines.push('<!-- proveit:begin -->');
  lines.push('## Capability contract');
  lines.push('');
  lines.push(
    `Generated by [proveit](https://github.com/Charcraft/proveit) v${result.version} on ${result.generatedAt}.`,
  );
  lines.push('Do not edit inside the `proveit` markers; re-run `proveit prompt --write AGENTS.md`.');
  lines.push('');
  lines.push('| Check | Status | Evidence |');
  lines.push('| --- | --- | --- |');
  for (const check of result.checks) {
    lines.push(`| \`${check.id}\` | **${STATUS_LABELS[check.status]}** | ${escapeCell(check.evidence)} |`);
  }
  lines.push('');
  lines.push('Rules for the agent:');
  lines.push('');
  lines.push('1. Never claim a limit ("sandbox", "no access", "no tool") that contradicts this table.');
  lines.push('2. Before asserting a limitation, test it with a real command and cite `[proveit:<id>=<status>]`.');
  lines.push('3. If a check is `blocked` or `unknown`, quote the exact error instead of guessing.');
  lines.push('4. Re-run `proveit probe` when the environment changes.');
  lines.push('<!-- proveit:end -->');
  return lines.join('\n');
}

/**
 * Replace an existing contract block or append a new one. Idempotent.
 */
export function upsertContract(existing, block) {
  const pattern = /<!-- proveit:begin -->[\s\S]*?<!-- proveit:end -->/;
  const trimmed = block.trim();
  if (pattern.test(existing)) {
    return existing.replace(pattern, trimmed);
  }
  const base = String(existing).trimEnd();
  return `${base}${base ? '\n\n' : ''}${trimmed}\n`;
}
